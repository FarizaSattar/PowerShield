import React, { useState, useEffect } from "react";

export default function PageHeader({ activePage }) {
  const [time, setTime] = useState(new Date().toLocaleTimeString());

  useEffect(() => {
    const timer = setInterval(() => setTime(new Date().toLocaleTimeString()), 1000);
    return () => clearInterval(timer);
  }, []);

  const getDetails = () => {
    switch (activePage) {
      case "devices":
        return { kicker: "ASSET INVENTORY & TELEMETRY", title: "Grid Infrastructure", desc: "Inspect live telemetry, grid voltage stability, active loads, and risk posture across all substations." };
      case "alerts":
        return { kicker: "THREAT INTELLIGENCE FEED", title: "Security Event Log", desc: "Examine threat triggers, anomaly flags, and severity classifications generated by the detection pipeline." };
      case "simulator":
        return { kicker: "CYBER-PHYSICAL ATTACK SIMULATOR", title: "Simulation Laboratory", desc: "Inject false sensor readings to test substation immunity and observe real-time defense responses." };
      default:
        return { kicker: "SECURITY OPERATIONS CENTER", title: "Grid Command Overview", desc: "Real-time AI-driven monitoring and intrusion detection for smart grid substations." };
    }
  };

  const { kicker, title, desc } = getDetails();

  return (
    <section className="page-heading">
      <div className="heading-left">
        <span className="page-kicker">{kicker}</span>
        <h1>{title}</h1>
        <p>{desc}</p>
      </div>
      <div className="heading-right">
        <div className="timestamp-badge">
          <span>UTC: {time}</span>
        </div>
      </div>
    </section>
  );
}